# Generates src/bigdigits.h: smooth 28x48 MM:SS digits + a narrow 10x48 colon, SSD1306 page format
# (byte = 8 vertical pixels, LSB on top). Rendered 4x from Bahnschrift Bold Condensed (narrow = tall digits:
# 43 px vs 32 px for Comic Sans) and box-downsampled, so edges
# are clean, not a scaled-up small font. Run: python tools/gen_bigdigits.py [preview.png]
import sys
from PIL import Image, ImageDraw, ImageFont

W, H, CW, SS = 28, 48, 10, 4
FONT, VARIANT = "C:/Windows/Fonts/bahnschrift.ttf", "Bold Condensed"


def fit():
    for size in range(100 * SS, 10, -1):
        f = ImageFont.truetype(FONT, size)
        f.set_variation_by_name(VARIANT)
        b = [f.getbbox(str(d)) for d in range(10)]
        if max(x[2] - x[0] for x in b) <= (W - 2) * SS and max(x[3] for x in b) - min(x[1] for x in b) <= (H - 2) * SS:
            return f, min(x[1] for x in b), max(x[3] for x in b)


def mono(img, w):
    return img.resize((w, H), Image.BOX).point(lambda v: 255 if v > 127 else 0)


def pages(img, w):
    px = img.load()
    return [sum((px[x, p * 8 + k] > 0) << k for k in range(8)) for p in range(H // 8) for x in range(w)]


f, top, bot = fit()
oy = (H * SS - (bot - top)) // 2 - top
digits = []
for d in range(10):
    img = Image.new("L", (W * SS, H * SS), 0)
    b = f.getbbox(str(d))
    ImageDraw.Draw(img).text(((W * SS - (b[2] - b[0])) // 2 - b[0], oy), str(d), font=f, fill=255)
    digits.append(mono(img, W))
img = Image.new("L", (CW * SS, H * SS), 0)
r, cx, mid, gap = 3.6 * SS, CW * SS / 2, H * SS / 2, (bot - top) * 0.22
for cy in (mid - gap, mid + gap):
    ImageDraw.Draw(img).ellipse((cx - r, cy - r, cx + r, cy + r), fill=255)
colon = mono(img, CW)

hex_ = lambda v: ", ".join("0x%02X" % b for b in v)
with open("src/bigdigits.h", "w") as o:
    o.write("// Generated by tools/gen_bigdigits.py (Bahnschrift Bold Condensed): 28x48 digits, 10x48 colon, SSD1306 pages.\n")
    o.write("#pragma once\n#include <avr/pgmspace.h>\n\nconst uint8_t BIG_W = %d, BIG_H = %d, COLON_W = %d;\n" % (W, H, CW))
    o.write("const uint8_t BIG_DIGITS[10][%d] PROGMEM = {\n" % (W * H // 8))
    o.write(",\n".join("  {%s}" % hex_(pages(g, W)) for g in digits) + "};\n")
    o.write("const uint8_t BIG_COLON[%d] PROGMEM = {%s};\n" % (CW * H // 8, hex_(pages(colon, CW))))

if len(sys.argv) > 1:  # preview of "20:00" on the 128x64 two-colour OLED, 4x
    scr = Image.new("RGB", (128, 64), (0, 0, 0))
    for x, g in zip((3, 31, 69, 97), (digits[2], digits[0], digits[0], digits[0])):
        scr.paste((60, 160, 255), (x, 16), g)
    scr.paste((60, 160, 255), (59, 16), colon)
    ImageDraw.Draw(scr).rectangle((0, 0, 127, 15), outline=None, fill=(40, 40, 0))
    scr.resize((512, 256), Image.NEAREST).save(sys.argv[1])
